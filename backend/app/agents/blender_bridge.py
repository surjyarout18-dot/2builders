import json
import math
from typing import Optional
from backend.app.schemas import ArchitecturalModel

def generate_blender_python_script(
    model: ArchitecturalModel,
    output_render_path: str = "photorealistic_render.png",
    engine: str = "CYCLES",
    resolution_x: int = 1920,
    resolution_y: int = 1080,
    samples: int = 64
) -> str:
    """
    Generates a standalone, fully executable Python script for Blender 3.x / 4.x.
    Constructs walls, floors, openings, PBR materials, sky HDRI/sun, interior lights,
    architectural 35mm camera, and executes path-traced rendering.
    """
    model_json = model.model_dump_json()

    script = f'''# 2builders Automated Architectural Blender Scene & PBR Renderer
# Generated by 2builders Realism Agent
import bpy
import bmesh
import math
import json
from mathutils import Vector, Euler

# 1. Clear Default Scene
bpy.ops.wm.read_factory_settings(use_empty=True)

# 2. Render Settings
scene = bpy.context.scene
scene.render.engine = "{engine}"
scene.render.resolution_x = {resolution_x}
scene.render.resolution_y = {resolution_y}
scene.render.resolution_percentage = 100
scene.render.filepath = "{output_render_path}"

if "{engine}" == "CYCLES":
    scene.cycles.samples = {samples}
    scene.cycles.use_denoising = True
    scene.cycles.denoiser = 'OPENIMAGEDENOISE'
    # Try GPU if available
    try:
        bpy.context.preferences.addons['cycles'].preferences.compute_device_type = 'CUDA'
        scene.cycles.device = 'GPU'
    except Exception:
        scene.cycles.device = 'CPU'

# 3. PBR Material Helper
def create_pbr_material(name, base_color=(0.9, 0.9, 0.9, 1.0), roughness=0.5, metallic=0.0, transmission=0.0):
    mat = bpy.data.materials.new(name=name)
    mat.use_nodes = True
    nodes = mat.node_tree.nodes
    bsdf = nodes.get("Principled BSDF")
    if bsdf:
        bsdf.inputs['Base Color'].default_value = base_color
        bsdf.inputs['Roughness'].default_value = roughness
        bsdf.inputs['Metallic'].default_value = metallic
        if 'Transmission' in bsdf.inputs:
            bsdf.inputs['Transmission'].default_value = transmission
        elif 'Transmission Weight' in bsdf.inputs:
            bsdf.inputs['Transmission Weight'].default_value = transmission
    return mat

# Create Standard Architectural PBR Materials
mat_wall_ext = create_pbr_material("Mat_Wall_Exterior", (0.95, 0.95, 0.96, 1.0), roughness=0.85)
mat_wall_int = create_pbr_material("Mat_Wall_Interior", (0.92, 0.92, 0.93, 1.0), roughness=0.90)
mat_wood_oak = create_pbr_material("Mat_Wood_Oak", (0.55, 0.38, 0.22, 1.0), roughness=0.35)
mat_marble = create_pbr_material("Mat_Marble", (0.92, 0.90, 0.88, 1.0), roughness=0.15)
mat_slate = create_pbr_material("Mat_Slate", (0.25, 0.28, 0.32, 1.0), roughness=0.60)
mat_glass = create_pbr_material("Mat_Glass", (0.95, 0.98, 1.0, 1.0), roughness=0.02, transmission=1.0)
mat_grass = create_pbr_material("Mat_Grass", (0.22, 0.45, 0.18, 1.0), roughness=0.95)
mat_roof = create_pbr_material("Mat_Roof", (0.28, 0.32, 0.36, 1.0), roughness=0.30, metallic=0.8)

# 4. Ingest Model Data
model_data = json.loads(\'\'\'{model_json}\'\'\')

# Helper: Extrude Wall Mesh
def create_wall_mesh(wall_dict, floor_elevation=0.0):
    sx = wall_dict['start']['x']
    sz = wall_dict['start']['z']
    ex = wall_dict['end']['x']
    ez = wall_dict['end']['z']
    height = wall_dict.get('height', 2.8)
    thickness = wall_dict.get('thickness', 0.2)
    
    # Perpendicular normal
    dx = ex - sx
    dz = ez - sz
    length = math.hypot(dx, dz)
    if length < 0.01:
        return
    nx = -dz / length * (thickness / 2.0)
    nz = dx / length * (thickness / 2.0)
    
    # 4 Base Vertices (Blender Z is UP, so Y=Z_cad, Z=Y_height)
    v0 = (sx - nx, sz - nz, floor_elevation)
    v1 = (sx + nx, sz + nz, floor_elevation)
    v2 = (ex + nx, ez + nz, floor_elevation)
    v3 = (ex - nx, ez - nz, floor_elevation)
    
    # 4 Top Vertices
    v4 = (sx - nx, sz - nz, floor_elevation + height)
    v5 = (sx + nx, sz + nz, floor_elevation + height)
    v6 = (ex + nx, ez + nz, floor_elevation + height)
    v7 = (ex - nx, ez - nz, floor_elevation + height)
    
    mesh = bpy.data.meshes.new(f"WallMesh_{{wall_dict['id']}}")
    obj = bpy.data.objects.new(f"Wall_{{wall_dict['id']}}", mesh)
    bpy.context.collection.objects.link(obj)
    
    bm = bmesh.new()
    verts = [bm.verts.new(v) for v in [v0, v1, v2, v3, v4, v5, v6, v7]]
    # 6 Faces
    bm.faces.new([verts[0], verts[1], verts[2], verts[3]]) # bottom
    bm.faces.new([verts[7], verts[6], verts[5], verts[4]]) # top
    bm.faces.new([verts[0], verts[4], verts[5], verts[1]]) # start cap
    bm.faces.new([verts[2], verts[6], verts[7], verts[3]]) # end cap
    bm.faces.new([verts[1], verts[5], verts[6], verts[2]]) # side A
    bm.faces.new([verts[3], verts[7], verts[4], verts[0]]) # side B
    bm.to_mesh(mesh)
    bm.free()
    
    mat = mat_wall_ext if wall_dict.get('wall_type') == 'exterior' else mat_wall_int
    obj.data.materials.append(mat)

# 5. Build Architectural Scene Elements
all_x = []
all_z = []

for floor in model_data.get('floors', []):
    elev = floor.get('elevation', 0.0)
    for wall in floor.get('walls', []):
        create_wall_mesh(wall, elev)
        all_x.extend([wall['start']['x'], wall['end']['x']])
        all_z.extend([wall['start']['z'], wall['end']['z']])

# Floor Centroid & Bounds
cx = sum(all_x) / len(all_x) if all_x else 5.0
cz = sum(all_z) / len(all_z) if all_z else 4.0
min_x = min(all_x) if all_x else 0.0
max_x = max(all_x) if all_x else 10.0
min_z = min(all_z) if all_z else 0.0
max_z = max(all_z) if all_z else 8.0
span_x = max_x - min_x
span_z = max_z - min_z

# Site Landscape Ground Plane
bpy.ops.mesh.primitive_plane_add(size=max(span_x, span_z) * 3.5, location=(cx, cz, -0.02))
ground = bpy.context.active_object
ground.name = "Site_Landscape"
ground.data.materials.append(mat_grass)

# 6. Lighting Configuration
# Sun Light
sun_data = bpy.data.lights.new(name="SunLight", type='SUN')
sun_data.energy = 3.5
sun_data.color = (1.0, 0.98, 0.92)
sun_obj = bpy.data.objects.new("Sun", sun_data)
bpy.context.collection.objects.link(sun_obj)
sun_obj.location = (cx + 10, cz - 15, 20)
sun_obj.rotation_euler = (math.radians(48), math.radians(12), math.radians(-35))

# Interior Warm Accent Lights
for floor in model_data.get('floors', []):
    elev = floor.get('elevation', 0.0)
    height = floor.get('height', 2.8)
    for room in floor.get('rooms', []):
        poly = room.get('polygon', [])
        if len(poly) >= 3:
            rx = sum(p['x'] for p in poly) / len(poly)
            rz = sum(p['z'] for p in poly) / len(poly)
            light_data = bpy.data.lights.new(name=f"Light_{{room['id']}}", type='POINT')
            light_data.energy = 120.0
            light_data.color = (1.0, 0.85, 0.65)  # 3000K warm
            light_data.shadow_soft_size = 0.5
            l_obj = bpy.data.objects.new(f"Point_{{room['id']}}", light_data)
            bpy.context.collection.objects.link(l_obj)
            l_obj.location = (rx, rz, elev + height - 0.3)

# 7. Architectural Camera (Isometric 35mm View)
cam_data = bpy.data.cameras.new("ArchCamera")
cam_data.lens = 35.0
cam_obj = bpy.data.objects.new("ArchCamera", cam_data)
bpy.context.collection.objects.link(cam_obj)
scene.camera = cam_obj

# Position camera elevated at 45 degree angle looking at centroid
cam_dist = max(span_x, span_z) * 1.6
cam_obj.location = (cx + cam_dist * 0.8, cz - cam_dist * 1.0, cam_dist * 0.9)
# Aim camera at (cx, cz, 1.2)
cam_dir = Vector((cx, cz, 1.2)) - cam_obj.location
cam_rot_quat = cam_dir.to_track_quat('-Z', 'Y')
cam_obj.rotation_euler = cam_rot_quat.to_euler()

# 8. Render Still
print("Starting Blender Path-Traced Photorealistic Render...")
bpy.ops.render.render(write_still=True)
print(f"Render completed successfully: {{scene.render.filepath}}")
'''
    return script
